const fs = require('fs');
const path = require('path');

/*
 * Build-time app version generator.
 *
 * Triggered by:
 * - android/app/build.gradle, generateAppBuildVersion task.
 * - ios/MovieApp.xcodeproj/project.pbxproj, "Generate app build version" phase.
 *
 * Next file in build flow:
 * - writeGeneratedVersionFile (line 111) writes
 *   src/appVersion/generatedBuildVersion.ts.
 *
 * Code flow:
 * 1. Android Gradle runs this script before Android builds through the
 *    generateAppBuildVersion task in android/app/build.gradle.
 * 2. Xcode runs this same script before iOS bundles JavaScript through the
 *    "Generate app build version" build phase in ios/MovieApp.xcodeproj.
 * 3. readIosVersion (line 90) and readAndroidVersion (line 68) read the native
 *    build settings for both platforms.
 * 4. writeGeneratedVersionFile (line 111) writes
 *    src/appVersion/generatedBuildVersion.ts.
 * 5. Runtime code imports that generated TypeScript file through
 *    src/appVersion/installedAppVersion.ts. The app never calls this script
 *    while the user is using Settings.
 *
 * Maintenance rule:
 * Change Android or iOS version numbers in the native build files, then run a
 * normal build. Do not hand-edit the generated TypeScript file because the
 * next build will replace it.
 */

const repoRoot = path.resolve(__dirname, '..');
const androidBuildGradlePath = path.join(
  repoRoot,
  'android',
  'app',
  'build.gradle'
);
const iosProjectPath = path.join(
  repoRoot,
  'ios',
  'MovieApp.xcodeproj',
  'project.pbxproj'
);
const generatedFilePath = path.join(
  repoRoot,
  'src',
  'appVersion',
  'generatedBuildVersion.ts'
);

function readFile(filePath) {
  return fs.readFileSync(filePath, 'utf8');
}

function requireMatch(source, regex, label) {
  const match = source.match(regex);

  if (!match) {
    throw new Error(`Could not read ${label}.`);
  }

  return match[1];
}

function readAndroidVersion() {
  const buildGradle = readFile(androidBuildGradlePath);
  const versionName = requireMatch(
    buildGradle,
    /versionName\s+["']([^"']+)["']/,
    'Android versionName'
  );
  const versionCode = Number(
    requireMatch(buildGradle, /versionCode\s+(\d+)/, 'Android versionCode')
  );

  if (!Number.isFinite(versionCode)) {
    throw new Error('Android versionCode is not a finite number.');
  }

  return {
    versionName,
    buildNumber: String(versionCode),
    versionCode,
  };
}

function readIosVersion() {
  const projectFile = readFile(iosProjectPath);
  const versionName = requireMatch(
    projectFile,
    /MARKETING_VERSION\s*=\s*([^;]+);/,
    'iOS MARKETING_VERSION'
  ).trim();
  const buildNumber = requireMatch(
    projectFile,
    /CURRENT_PROJECT_VERSION\s*=\s*([^;]+);/,
    'iOS CURRENT_PROJECT_VERSION'
  ).trim();
  const versionCode = Number(buildNumber);

  return {
    versionName,
    buildNumber,
    versionCode: Number.isFinite(versionCode) ? versionCode : null,
  };
}

function writeGeneratedVersionFile(version) {
  fs.mkdirSync(path.dirname(generatedFilePath), { recursive: true });

  const fileContents = `/*
 * Generated installed-version snapshot.
 *
 * Imported by:
 * - src/appVersion/installedAppVersion.ts imports INSTALLED_APP_VERSION.
 *
 * Next file in UI flow:
 * - src/appVersion/installedAppVersion.ts reads this exported snapshot.
 *
 * No function calls:
 * - This generated file calls nothing. It only exports INSTALLED_APP_VERSION
 *   from line 27.
 *
 * Code flow:
 * 1. scripts/generate-app-build-version.js creates this file during Android
 *    and iOS builds.
 * 2. src/appVersion/installedAppVersion.ts imports this constant at app
 *    runtime and selects the current platform.
 * 3. src/drawer/SettingsScreen.tsx compares this installed version with the
 *    store version returned by src/api/appVersion.ts.
 *
 * Maintenance rule:
 * Do not edit this file directly. Change Android or iOS build version settings
 * instead, then run a normal build so this file is regenerated.
 */

export const INSTALLED_APP_VERSION = ${JSON.stringify(version, null, 2)} as const;
`;

  fs.writeFileSync(generatedFilePath, fileContents);
}

const installedAppVersion = {
  ios: readIosVersion(),
  android: readAndroidVersion(),
};

writeGeneratedVersionFile(installedAppVersion);

console.log(
  `Generated ${path.relative(repoRoot, generatedFilePath)} from native build settings.`
);
